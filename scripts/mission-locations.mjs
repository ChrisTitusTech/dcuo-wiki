export function missionAreaPattern() {
  const alternatives = [...new Set(names)]
    .sort((a, b) => b.length - a.length || a.localeCompare(b))
    .map((name) =>
      name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replaceAll("'", "['’]"),
    );
  return new RegExp("\\b(?:" + alternatives.join("|") + ")(?=\\W|$)", "gi");
}
